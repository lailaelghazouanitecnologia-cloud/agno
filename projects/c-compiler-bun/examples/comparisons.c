int main() {
    int a = 10;
    int b = 20;
    
    // Less than
    printf("%d < %d = %d\n", a, b, a < b);
    
    // Greater than
    printf("%d > %d = %d\n", a, b, a > b);
    
    // Less than or equal
    printf("%d <= %d = %d\n", a, b, a <= b);
    
    // Greater than or equal
    printf("%d >= %d = %d\n", a, b, a >= b);
    
    // Equal
    printf("%d == %d = %d\n", a, b, a == b);
    
    // Not equal
    printf("%d != %d = %d\n", a, b, a != b);
    
    return 0;
}