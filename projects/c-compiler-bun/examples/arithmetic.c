// Arithmetic operations example
int main() {
  int a = 10;
  int b = 5;
  
  int sum = a + b;
  int diff = a - b;
  int product = a * b;
  int quotient = a / b;
  int remainder = a % b;
  
  printf("Sum: %d\n", sum);
  printf("Difference: %d\n", diff);
  printf("Product: %d\n", product);
  printf("Quotient: %d\n", quotient);
  printf("Remainder: %d\n", remainder);
  
  return 0;
}