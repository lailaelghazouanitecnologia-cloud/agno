int main() {
    // Integer variables
    int x = 10;
    int y = 20;
    
    // Character variable
    char c = 'A';
    
    // Float variable
    float f = 3.14;
    
    // Print all variables
    printf("x = %d\n", x);
    printf("y = %d\n", y);
    printf("c = %c\n", c);
    printf("f = %f\n", f);
    
    return 0;
}