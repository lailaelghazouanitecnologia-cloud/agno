// Control flow example
int main() {
  int x = 10;
  
  // If-else statement
  if (x > 5) {
    printf("x is greater than 5\n");
  } else {
    printf("x is not greater than 5\n");
  }
  
  // While loop
  int i = 0;
  while (i < 5) {
    printf("While loop: i = %d\n", i);
    i = i + 1;
  }
  
  // For loop
  for (int j = 0; j < 3; j = j + 1) {
    printf("For loop: j = %d\n", j);
  }
  
  return 0;
}